/** 요일 글자 → 0(일)~6(토) */
export const DOW: Readonly<Record<string, number>> = { 일: 0, 월: 1, 화: 2, 수: 3, 목: 4, 금: 5, 토: 6 };

/** '…요일' */
export const DOW_NAME = /([월화수목금토일])요일/g;
/** 구분점으로 이은 요일들(뒤에 요일·마다·에가 붙어도 된다): 화·목, 월/수/금 */
export const DOW_LIST = /(?:^|[^가-힣])([월화수목금토일](?:\s*[·,\/]\s*[월화수목금토일])+)(?=요일|마다|에|$|[^가-힣])/g;
export const DOW_LIST_SEP = /[\s·,\/]/g;
/** 붙여 쓴 요일: 세 글자 이상(월수금), 또는 뒤에 요일·마다가 붙은 두 글자(화목마다) */
export const DOW_RUN = /(?:^|[^가-힣])([월화수목금토일]{2,7})(요일|마다)?(?=$|[^가-힣])/g;

/** 주 N회 · 일주일에 N번 · 한 주에 N번 · 주 1통화 · 주 3~4회(적은 쪽을 목표로) */
export const PER_WEEK = /(?:주|일주일에?|1주일에?|한\s*주에?|매주)\s*(\d)(?:\s*[~\-–]\s*\d)?\s*(?:회|번|통|차례)/;
/** 한 달 단위는 아직 다루지 않으니 고르지 않는다(월 50만 원 저축, 한 달 한 권) */
export const MONTHLY = /매월|매달|한\s*달에|한\s*달\s*한|(?:^|\s)월\s*\d/;
export const WEEKDAYS = /평일/;
export const WEEKENDS = /주말/;
export const WEEKLY = /매주/;

/** 날마다 하는 일로 읽히는 말 */
export const DAILY_WORDS = /매일|날마다|하루|아침마다|저녁마다|밤마다|자기\s*전|잠들기\s*전|일어나(?:서|자마자)|매\s*끼|식후|출근\s*(?:길|전|후)|퇴근\s*(?:길|전|후)|점심\s*(?:후|시간)|아침에|저녁에|매일매일/;
/** '공부 2시간'처럼 짧은 시간은 날마다, '봉사 20시간'처럼 긴 시간은 쌓기 */
export const HOURS = /(\d+(?:\.\d+)?)\s*시간/;
/** 시간 길이·시각·걸음·물·일기 — 대개 날마다 */
export const DAILY_HINTS: readonly RegExp[] = [
  /\d+\s*분(?!기|량|야)/, // 10분 (분기·분량 제외)
  /\d+\s*시\s*(?:전|이전|까지)?\s*(?:에\s*)?(?:자기|잠들기|취침|기상|일어나기)/,
  /취침|기상/,
  /\d[\d,]*\s*(?:만\s*)?(?:보|걸음)/, // 1만보, 8000걸음
  /물\s*\d/,
  /일기|저널/,
  /\d+\s*(?:쪽|페이지)/,
];

export const MIND = /감사|경청|긍정|배려|존중|겸손|칭찬|미소|웃는|웃기|인사|친절|여유|태도|마음가짐|화내지|화\s*안|불평|험담|비교하지|조급|침착|솔직|정직|예의|너그럽|공감|용서|감정/;
export const ONCE = /취득|합격|따기|등록|신청|갱신|완성|출간|출시|마련|구입|구매|장만|예약|이사|검진|접종|완주|완강|수료|졸업|도전|찾기|가기|다녀오기|떠나기|보기|정리|끝내기|마치기|성공/;

/** 쌓기로 읽히는 단위 — 앞의 것이 먼저 맞는다(개국 > 개) */
export const COUNT_UNIT = /(\d[\d,]*(?:\.\d+)?)\s*(만\s*원|천\s*원|원|개국|권|곳|군데|가지|개(?!월)|편|곡|명|장|통|그루|건|번|회|km|킬로미터|kg|킬로그램|시간)/i;
/** 띄어 써야 읽기 쉬운 돈 단위 — '만원' → '만 원' (kinds.cleanUnit도 쓴다) */
export const MONEY_SPACE: ReadonlyMap<string, string> = new Map([['만원', '만 원'], ['천원', '천 원']]);
/** 줄여 쓰는 단위 */
export const UNIT_ALIAS: ReadonlyMap<string, string> = new Map([['킬로미터', 'km'], ['킬로그램', 'kg']]);
/** 한 번이면 끝나는 단위('발표 1회', '기술 1개') */
export const SINGLE_UNITS: ReadonlySet<string> = new Set(['번', '회', '개', '곳', '군데', '가지', '편', '권', '건', '통']);
/** 짧은 거리는 한 번 뛰는 양인지 쌓을 양인지 알 수 없어 고르지 않는다 — 이 거리(km) 아래 */
export const SHORT_KM = 30;

// ── 끝이 있는 기록 · 닿을 수준 — 날마다 하는 일이나 쌓기로 읽지 않는다(반복하는 말이 없을 때) ──────────

/** 시간 길이 — '2시간' · '55분' · '12초'(분기 · 분량 · 분야, '11시 30분' 같은 시각은 아니다) */
export const DURATION = /(?<![\d.])(?<!\d\s*시\s*)\d+(?:\.\d+)?\s*(?:시간|분(?![기량야])|초(?![등급과반]))/;
/** 시간 길이에 붙은 한도 — '2시간 안에' · '55분 이내' · '4시간 30분까지' · '50분대'(시각 '11시 30분까지'는 아니다) */
export const TIME_LIMIT = /(?<![\d.])(?<!\d\s*시\s*)\d+(?:\.\d+)?\s*(?:시간|분|초)\s*(?:\d+\s*(?:분|초)\s*)*(?:안에|안으로|이내|내에|내로|까지|대(?![가-힣])|언더)/;
/** 기록을 재는 말 — 시간 길이와 함께 나오면 끝이 있는 기록이다('30분 완주', '최고 기록 50분'). 적어 남기는 '기록하기'는 아니다 */
export const RECORD = /완주|완영|주파|(?:최고|개인|신)\s*기록|기록\s*(?:단축|경신|갱신|돌파)/;
/** 경기 · 거리 — 시간 길이와 함께 나오면 걸린 시간을 재는 목표다('풀코스 4시간 30분', '10km 55분') */
export const RACE = /풀\s*코스|하프|마라톤|철인|트라이애슬론|울트라|\d+(?:\.\d+)?\s*(?:km|킬로미터|미터|k(?![a-z가-힣])|m(?![a-z가-힣]))/i;
/** 날마다 하는 일로 남길 말 — 잠드는 시각, 몸풀기 · 연습 · 걷기('30분 안에 잠들기', '마라톤 훈련 1시간', '걷기 5km 1시간') */
export const ROUTINE = /자기|잠들|취침|기상|일어나|연습|훈련|트레이닝|스트레칭|조깅|산책|걷/;
/** 마라톤 기록을 부르는 말 — '서브4'(시간 길이가 없어도 기록이다) */
export const SUB_TIME = /서브\s*-?\s*[2-6]/;

/** 닿을 수준을 재는 단위 — '15%' · '900점' · '1등' · '2급'(점심 · 등산 · 급하게 같은 말은 아니다) */
export const LEVEL = /\d[\d,]*(?:\.\d+)?\s*(?:%|퍼센트|프로(?![가-힣])|점(?![심검포])|등급|등(?![산록])|급(?![가-힣]))/;
/** 몸무게 · 들어 올리는 무게는 수준이다('몸무게 65kg'). 덜고 더하는 말이 있을 때만 그만큼을 쌓는다('3kg 감량') */
export const KG_CHANGE = /감량|증량|빼|뺀|뺄|줄이|줄인|늘리|늘린|찌우|불리|다이어트|벌크/;
/** 덜고 더하는 말이 있어도 닿을 수준인 꼴 — '65kg까지 감량' · '70kg대' · '65kg 만들기' · '60kg 유지' */
export const KG_TARGET = /(?:kg|킬로그램)\s*(?:까지|대(?![가-힣])|(?:으)?로\s|만들|유지|달성|도달)/i;
/** 한 번에 해내는 횟수로 읽히는 운동 — '턱걸이 10개'는 0에서 쌓아 가는 수가 아니라 닿을 수준이다 */
export const REPS = /턱걸이|풀업|친업|푸시업|푸쉬업|팔\s*굽혀\s*펴기|윗몸\s*일으키기|싯업|스쿼트|버피|런지|딥스|머슬업|줄넘기|물구나무/;
export const REP_UNITS: ReadonlySet<string> = new Set(['개', '회', '번']);
