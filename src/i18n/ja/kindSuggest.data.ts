/** '日曜' · '月曜日'。前に漢字が付くと曜日ではない（'毎日曜'は例外的に通す） */
export const DOW_NAME = /([月火水木金土日])曜/g;
/** 区切りでつないだ曜日: 月・水・金、火/木、月、水、金 — 前後が漢字なら別の語 */
export const DOW_LIST = /(?:^|[^一-鿿々]|週)([月火水木金土日](?:\s*[・,、\/]\s*[月火水木金土日])+)(?=曜|[^一-鿿々]|$)/g;
export const DOW_LIST_SEP = /[\s・,、\/]/g;
/** 続けて書いた曜日: 3字以上（月水金）、または「に・は・ごと・曜」が後に付く2字（火木に） — '水木' '月日' のような語は通さない */
export const DOW_RUN = /(?:^|[^一-鿿々]|週)([月火水木金土日]{2,7})(曜|に|ごと|は)?(?=[^一-鿿々]|$)/g;

/** 週3回 · 週に3回 · 週3日 · 1週間に2回 · 週2〜3回（少ない方） · 週三回 */
export const PER_WEEK = /(?:毎週|週に?|1週間に?|一週間に?)\s*([1-7一二三四五六七])(?:\s*[~〜\-–]\s*[0-9一二三四五六七])?\s*(?:回|日|度)/;
/** 月単位はまだ扱わないので選ばない（毎月5万円、月に1冊） */
